"""Design system: theme source, stylesheet generation and contrast."""
import tomllib
from dataclasses import dataclass
from itertools import starmap
from pathlib import Path
from typing import Any
from typing import Final

from term_timer.constants import STATIC_DIRECTORY

THEME_FILE: Final = Path(__file__).parent / 'theme.toml'

CSS_DIRECTORY: Final = STATIC_DIRECTORY / 'css'

THEME_STYLESHEET: Final = CSS_DIRECTORY / 'theme.css'

CONTRAST_LEVELS: Final = {
    'text': 7.0,
    'large': 4.5,
}

SRGB_LINEAR_LIMIT: Final = 0.03928

LAYERS: Final = ('theme', 'base', 'layout', 'components', 'pages')

VALUE_SECTIONS: Final = (
    ('Space', 'space'),
    ('Lines', 'line'),
    ('Motion', 'motion'),
)

HEADER: Final = (
    '/* Generated by `python -m term_timer.server.design` from theme.toml.\n'
    '   Do not edit: change theme.toml and regenerate. */\n'
)


@dataclass(frozen=True)
class ThemeToken:
    """One custom property of the theme."""

    name: str
    value: str
    note: str = ''


@dataclass(frozen=True)
class ThemeGroup:
    """A titled family of custom properties."""

    title: str
    tokens: tuple[ThemeToken, ...]


@dataclass(frozen=True)
class ContrastCheck:
    """A declared text/background pair and its measured contrast."""

    text: str
    background: str
    level: str
    ratio: float

    @property
    def minimum(self) -> float:
        """
        Minimal ratio required by the pair's level.

        Returns:
            The WCAG threshold of the level.

        """
        return CONTRAST_LEVELS[self.level]

    @property
    def passed(self) -> bool:
        """
        Whether the pair reaches its level.

        Returns:
            True when the ratio is at least the minimum.

        """
        return self.ratio >= self.minimum


class DesignTheme:
    """The theme read from theme.toml."""

    def __init__(self, data: dict[str, Any]) -> None:
        """
        Validate and keep the raw theme data.

        Args:
            data: Parsed content of theme.toml.

        Raises:
            ValueError: A role names an unknown palette colour, or a
                contrast pair an unknown level.

        """
        self.palette: dict[str, str] = dict(data['palette'])
        self.roles: dict[str, str] = dict(data['roles'])
        self.type: dict[str, dict[str, Any]] = dict(data['type'])
        self.sections: dict[str, dict[str, str]] = {
            key: dict(data[key]) for _title, key in VALUE_SECTIONS
        }
        self.contrast: list[dict[str, str]] = list(data.get('contrast', []))

        for role, colour in self.roles.items():
            if colour not in self.palette:
                message = f'Role { role } names unknown colour { colour }'
                raise ValueError(message)

        for pair in self.contrast:
            if pair['level'] not in CONTRAST_LEVELS:
                message = f'Unknown contrast level { pair["level"] }'
                raise ValueError(message)

    @classmethod
    def load(cls, path: Path = THEME_FILE) -> 'DesignTheme':
        """
        Read a theme file.

        Returns:
            The validated theme.

        """
        with path.open('rb') as handle:
            return cls(tomllib.load(handle))

    def colour(self, name: str) -> str:
        """
        Resolve a role or palette name to its hexadecimal colour.

        Returns:
            The colour as written in the palette.

        """
        return self.palette[self.roles.get(name, name)]

    @staticmethod
    def luminance(colour: str) -> float:
        """
        Relative luminance of a #rrggbb colour, as defined by WCAG.

        Returns:
            The luminance, between 0 and 1.

        """
        channels = [
            int(colour[index:index + 2], 16) / 255
            for index in (1, 3, 5)
        ]
        linear = [
            value / 12.92 if value <= SRGB_LINEAR_LIMIT
            else ((value + 0.055) / 1.055) ** 2.4
            for value in channels
        ]
        return 0.2126 * linear[0] + 0.7152 * linear[1] + 0.0722 * linear[2]

    @classmethod
    def contrast_ratio(cls, first: str, second: str) -> float:
        """
        WCAG contrast ratio between two #rrggbb colours.

        Returns:
            The ratio, between 1 and 21.

        """
        lighter, darker = sorted(
            (cls.luminance(first), cls.luminance(second)),
            reverse=True,
        )
        return (lighter + 0.05) / (darker + 0.05)

    def contrast_checks(self) -> list[ContrastCheck]:
        """
        Measure every declared contrast pair.

        Returns:
            One check per pair, in declaration order.

        """
        return [
            ContrastCheck(
                text=pair['text'],
                background=pair['background'],
                level=pair['level'],
                ratio=self.contrast_ratio(
                    self.colour(pair['text']),
                    self.colour(pair['background']),
                ),
            )
            for pair in self.contrast
        ]

    def root_size(self) -> str:
        """
        Fluid root font size, linear between the two viewport bounds.

        Returns:
            A CSS clamp() expression.

        """
        fluid = self.type['fluid']
        slope = (fluid['max-size'] - fluid['min-size']) / (
            fluid['max-viewport'] - fluid['min-viewport']
        )
        intercept = fluid['min-size'] - slope * fluid['min-viewport']
        return (
            f'clamp({ fluid["min-size"] }px,'
            f' { intercept:.4g}px + { slope * 100:.4g}vw,'
            f' { fluid["max-size"] }px)'
        )

    def groups(self) -> list[ThemeGroup]:
        """
        Every custom property of the theme, grouped by family.

        Returns:
            The groups in stylesheet order.

        """
        groups = [
            ThemeGroup('Root', (
                ThemeToken('root-size', self.root_size()),
            )),
            ThemeGroup('Palette', tuple(
                starmap(ThemeToken, self.palette.items()),
            )),
            ThemeGroup('Roles', tuple(
                ThemeToken(role, f'var(--{ colour })', self.colour(role))
                for role, colour in self.roles.items()
            )),
            ThemeGroup('Type', tuple(
                ThemeToken(name, value)
                for section in ('families', 'scale')
                for name, value in self.type[section].items()
            )),
        ]
        groups.extend(
            ThemeGroup(title, tuple(
                starmap(ThemeToken, self.sections[key].items()),
            ))
            for title, key in VALUE_SECTIONS
        )
        return groups

    def stylesheet(self) -> str:
        """
        Render the theme as its stylesheet.

        Returns:
            The content of theme.css.

        """
        lines = [
            HEADER,
            f'@layer { ", ".join(LAYERS) };',
            '',
            '@layer theme {',
            '  :root {',
            '    color-scheme: dark;',
        ]
        for group in self.groups():
            lines.extend(('', f'    /* { group.title } */'))
            lines.extend(
                f'    --{ token.name }: { token.value };'
                for token in group.tokens
            )
        lines.extend(('  }', '}', ''))
        return '\n'.join(lines)
